const m = ([x, y]: P): P => [400 - x, y]
const pt = ([x, y]: P) => `${x},${y}`

function buildBody() {
  let d = `M${pt(START)}`
  for (const [c1, c2, p] of LEFT) d += ` C${pt(c1)} ${pt(c2)} ${pt(p)}`
  const pts: P[] = [START, ...LEFT.map((s) => s[2])]
  for (let i = LEFT.length - 1; i >= 0; i--) {
    const [c1, c2] = LEFT[i]
    d += ` C${pt(m(c2))} ${pt(m(c1))} ${pt(m(pts[i]))}`
  }
  return d + ' Z'
}

