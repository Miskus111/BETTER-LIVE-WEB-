/**
 * Generates supabase/seed.sql (global reference data) from the typed modules in src/data:
 * USDA foods and the affiliate product catalogue. Run: `npm run gen:seed`.
 * Demo user + personal demo data: `npm run seed:demo` (needs SUPABASE_SERVICE_ROLE_KEY).
 */
import { writeFileSync } from 'node:fs'
import { FOODS } from '../src/data/foods'
import { WHERE_TO_BUY, TOPIC_LINKS, type ShopLink } from '../src/data/retailers'

const q = (v: unknown) =>
  v === null || v === undefined
    ? 'null'
    : typeof v === 'number'
      ? String(v)
      : `'${String(v).replace(/'/g, "''")}'`
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`

const lines: string[] = [
  '-- GENERATED by scripts/gen-seed.ts — do not edit by hand.',
  '-- Global reference data (owner_id null). Safe to re-run.',
  '',
  '-- foods (USDA FoodData Central, per 100 g)',
]
for (const f of FOODS) {
  lines.push(
    `insert into public.foods (owner_id, source, source_id, slug, name_cs, name_en, kcal, protein_g, fat_g, carbs_g, fiber_g, micros) values (null, 'usda', ${q(f.fdc)}, ${q(f.id)}, ${q(f.name)}, ${q(f.id.replace(/-/g, ' '))}, ${f.kcal}, ${f.macros.protein}, ${f.macros.fat}, ${f.macros.carbs}, ${f.macros.fiber}, ${j(f.micros)}) on conflict (owner_id, slug) do update set kcal = excluded.kcal, protein_g = excluded.protein_g, fat_g = excluded.fat_g, carbs_g = excluded.carbs_g, fiber_g = excluded.fiber_g, micros = excluded.micros;`,
  )
}

lines.push('', '-- affiliate product catalogue')
const slug = (l: ShopLink) =>
  `${l.retailer}-${new URL(l.url).pathname.replace(/\//g, '-').replace(/^-|-$/g, '')}`
const rows = new Map<string, { l: ShopLink; nutrient: string | null }>()
for (const [nutrient, links] of Object.entries(WHERE_TO_BUY))
  for (const l of links ?? []) rows.set(slug(l), { l, nutrient })
for (const [topic, links] of Object.entries(TOPIC_LINKS))
  for (const l of links) rows.set(slug(l), { l, nutrient: topic })
for (const [s, { l, nutrient }] of rows) {
  const kind = l.kind === 'doplněk' ? 'supplement' : l.kind === 'kategorie' ? 'category' : 'food'
  lines.push(
    `insert into public.products (slug, retailer, name, url, kind, nutrient, why, note) values (${q(s)}, ${q(l.retailer)}, ${q(l.label)}, ${q(l.url)}, ${q(kind)}, ${q(nutrient)}, ${q(l.why)}, ${q(l.note)}) on conflict (slug) do update set name = excluded.name, url = excluded.url, why = excluded.why, note = excluded.note;`,
  )
}

writeFileSync('supabase/seed.sql', lines.join('\n') + '\n')
console.log(`supabase/seed.sql: ${FOODS.length} foods, ${rows.size} products`)
